#!/usr/bin/env bash
# Installs or updates CampusBite on Ubuntu (20.04+). Run as root by deploy/deploy.sh.
# Idempotent: re-running keeps the database, secrets (.env) and uploaded data.
#
# Layout:  /opt/campusbite/backend   API code, .venv, .env (secrets, mode 600)
#          /opt/campusbite/web       static apps: / student, /kitchen/, /admin/
# Services: campusbite-api (uvicorn, 2 workers), campusbite-worker, nginx, postgresql, redis
set -euo pipefail

RELEASE=$(cd "$(dirname "$0")/.." && pwd)
APP=/opt/campusbite
PUBLIC_URL=${PUBLIC_URL:?PUBLIC_URL is required}
DOMAIN=${DOMAIN:-}
CERTBOT_EMAIL=${CERTBOT_EMAIL:-}
export DEBIAN_FRONTEND=noninteractive

log() { printf '\n==> %s\n' "$*"; }
cd /  # commands run as other users (postgres, campusbite) can't read the SSH user's home

log "System packages"
apt-get update -y -qq
apt-get install -y -qq nginx postgresql redis-server python3 python3-venv curl ca-certificates openssl >/dev/null

# Small instances (1 GB) can run out of memory while installing packages: add swap once.
if ! swapon --show | grep -q . && [ "$(awk '/MemTotal/ {print $2}' /proc/meminfo)" -lt 2000000 ]; then
  log "Adding 1 GB swap"
  fallocate -l 1G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

systemctl enable --now postgresql redis-server >/dev/null

log "App user and files"
id campusbite >/dev/null 2>&1 || useradd --system --home-dir "$APP" --shell /usr/sbin/nologin campusbite
mkdir -p "$APP/backend"
# Replace code but keep the virtualenv and secrets.
find "$APP/backend" -mindepth 1 -maxdepth 1 ! -name .venv ! -name .env -exec rm -rf {} +
cp -a "$RELEASE/backend/." "$APP/backend/"
rm -rf "$APP/web.new" && cp -a "$RELEASE/web" "$APP/web.new"
rm -rf "$APP/web.old" && { [ -d "$APP/web" ] && mv "$APP/web" "$APP/web.old" || true; } && mv "$APP/web.new" "$APP/web"
chown -R campusbite:campusbite "$APP"
chmod 755 "$APP" "$APP/web"

log "Database and secrets"
ENV_FILE="$APP/backend/.env"
if [ ! -f "$ENV_FILE" ]; then
  DB_PASS=$(openssl rand -hex 24)
  if sudo -u postgres psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='campusbite'" | grep -q 1; then
    sudo -u postgres psql -qc "ALTER ROLE campusbite WITH LOGIN PASSWORD '$DB_PASS'"
  else
    sudo -u postgres psql -qc "CREATE ROLE campusbite WITH LOGIN PASSWORD '$DB_PASS'"
  fi
  sudo -u postgres psql -tAc "SELECT 1 FROM pg_database WHERE datname='campusbite'" | grep -q 1 \
    || sudo -u postgres createdb -O campusbite campusbite
  PILOT_OTP=$(shuf -i 100000-999999 -n 1)
  [ "$PILOT_OTP" != 123456 ] || PILOT_OTP=654321  # never the public dev code
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by deploy/server-setup.sh. Keep this file secret.
ENV=production
DATABASE_URL=postgresql+psycopg://campusbite:${DB_PASS}@127.0.0.1:5432/campusbite
REDIS_URL=redis://127.0.0.1:6379/0
JWT_SECRET=$(openssl rand -hex 32)
WEBHOOK_SECRET=$(openssl rand -hex 24)
# No SMS provider yet: everyone logs in with this pilot OTP. Share it only with pilot users.
OTP_FIXED_CODE=$PILOT_OTP
CORS_ORIGINS=$PUBLIC_URL
RUN_WORKER=false
RUN_MIGRATIONS=false
EOF
  umask 022
fi
sed -i "s#^CORS_ORIGINS=.*#CORS_ORIGINS=$PUBLIC_URL#" "$ENV_FILE"
chown campusbite:campusbite "$ENV_FILE" && chmod 600 "$ENV_FILE"

log "Python environment"
cd "$APP/backend"
if python3 -c 'import sys; sys.exit(0 if sys.version_info >= (3, 10) else 1)'; then
  [ -x .venv/bin/python ] || sudo -u campusbite python3 -m venv .venv
  sudo -u campusbite .venv/bin/pip install -q --upgrade pip
  sudo -u campusbite .venv/bin/pip install -q -r requirements.txt
else
  # Old Ubuntu: get Python 3.12 through uv.
  command -v uv >/dev/null || curl -LsSf https://astral.sh/uv/install.sh | env UV_INSTALL_DIR=/usr/local/bin UV_NO_MODIFY_PATH=1 sh
  [ -x .venv/bin/python ] || sudo -u campusbite env UV_PYTHON_INSTALL_DIR="$APP/.python" uv venv --python 3.12 .venv
  sudo -u campusbite uv pip install -q --python .venv/bin/python -r requirements.txt
fi

log "Migrations and first-run demo data"
sudo -u campusbite .venv/bin/python -c "from app.migrate import upgrade_db; upgrade_db()"
sudo -u campusbite .venv/bin/python seed.py --if-empty

log "Services"
cat > /etc/systemd/system/campusbite-api.service <<EOF
[Unit]
Description=CampusBite API
After=network-online.target postgresql.service redis-server.service
Wants=network-online.target

[Service]
User=campusbite
Group=campusbite
WorkingDirectory=$APP/backend
ExecStartPre=$APP/backend/.venv/bin/python -c "from app.migrate import upgrade_db; upgrade_db()"
ExecStart=$APP/backend/.venv/bin/uvicorn app.main:app --host 127.0.0.1 --port 8000 --workers 2 --proxy-headers --forwarded-allow-ips 127.0.0.1
Restart=always
RestartSec=3
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true

[Install]
WantedBy=multi-user.target
EOF
cat > /etc/systemd/system/campusbite-worker.service <<EOF
[Unit]
Description=CampusBite background jobs (payment expiry, refunds, late-order alerts)
After=network-online.target postgresql.service redis-server.service

[Service]
User=campusbite
Group=campusbite
WorkingDirectory=$APP/backend
ExecStart=$APP/backend/.venv/bin/python -m app.worker
Restart=always
RestartSec=5
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=full
ProtectHome=true

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable campusbite-api campusbite-worker >/dev/null
systemctl restart campusbite-api campusbite-worker

log "Nginx"
install -m 644 "$RELEASE/deploy/nginx-headers.conf" /etc/nginx/snippets/campusbite-headers.conf
sed -e "s#__PORT__#80#g" -e "s#__SERVER_NAME__#${DOMAIN:-_}#g" -e "s#__WEB_ROOT__#$APP/web#g" \
    -e "s#__API__#127.0.0.1:8000#g" -e "s#__HEADERS__#snippets/campusbite-headers.conf#g" \
    "$RELEASE/deploy/nginx-campusbite.conf" > /etc/nginx/sites-available/campusbite
ln -sf /etc/nginx/sites-available/campusbite /etc/nginx/sites-enabled/campusbite
rm -f /etc/nginx/sites-enabled/default
nginx -t -q
systemctl reload nginx || systemctl restart nginx

if [ -n "$DOMAIN" ]; then
  log "HTTPS for $DOMAIN"
  apt-get install -y -qq certbot python3-certbot-nginx >/dev/null
  certbot --nginx -d "$DOMAIN" --non-interactive --agree-tos -m "$CERTBOT_EMAIL" --redirect
fi

if ufw status 2>/dev/null | grep -q "Status: active"; then
  ufw allow OpenSSH >/dev/null && ufw allow 'Nginx Full' >/dev/null
fi

log "Daily database backups (kept 14 days in /var/backups/campusbite)"
install -d -m 700 -o postgres -g postgres /var/backups/campusbite
cat > /etc/cron.daily/campusbite-backup <<'EOF'
#!/bin/sh
set -e
sudo -u postgres pg_dump -Fc campusbite > /var/backups/campusbite/campusbite-$(date +%F).dump
find /var/backups/campusbite -name '*.dump' -mtime +14 -delete
EOF
chmod 755 /etc/cron.daily/campusbite-backup

log "Health check"
for i in $(seq 1 30); do
  curl -fsS http://127.0.0.1:8000/health >/dev/null 2>&1 && break
  sleep 2
done
if ! curl -fsS http://127.0.0.1:8000/health; then
  echo "API did not start. Last log lines:" >&2
  journalctl -u campusbite-api -n 40 --no-pager >&2
  exit 1
fi
echo
systemctl is-active --quiet campusbite-worker || { journalctl -u campusbite-worker -n 40 --no-pager >&2; exit 1; }
curl -fsS -o /dev/null http://127.0.0.1/ || curl -fsSk -o /dev/null "https://127.0.0.1/" \
  || { echo "Nginx is not serving the apps" >&2; exit 1; }

OTP=$(grep '^OTP_FIXED_CODE=' "$ENV_FILE" | cut -d= -f2)
cat <<EOF

CampusBite is live
  Student app:  $PUBLIC_URL/
  Kitchen app:  $PUBLIC_URL/kitchen/
  Admin:        $PUBLIC_URL/admin/
  API docs:     $PUBLIC_URL/docs
  Pilot OTP:    ${OTP:-"(SMS provider)"}   (super admin phone 9000000000)
  Logs:         journalctl -u campusbite-api -u campusbite-worker -f
EOF
